// `satisfies` checks the shape without widening or narrowing it: a missing
// Chinese key is a compile error, and `typeof zh` stays useful for inference.
// `satisfies` validates the shape without widening or narrowing either side:
// a missing Chinese key is a compile error, and `typeof zh` stays precise
// enough for the translator below.
export const dictionaries = { en, zh } satisfies Record<LocaleCode, typeof en>;

export type Dictionary = typeof en;

/** Dotted key into the dictionary tree. */
type Path<T, Prefix extends string = ''> = {
  [K in keyof T & string]: T[K] extends (...args: never[]) => unknown
    ? `${Prefix}${K}`
    : T[K] extends object
      ? Path<T[K], `${Prefix}${K}.`>
      : `${Prefix}${K}`;
}[keyof T & string];

export type TranslationKey = Path<typeof en>;

const KEY_RE = /^[a-zA-Z0-9_]+(\.[a-zA-Z0-9_]+)+$/;

/**
 * Translates a key. Missing keys fall back to English, then to the key itself
 * so a missing string is visible rather than silently blank.
 *
 * Values may be a string or a function (`t('search.resultsCount', 5)`).
 */
export function translate(
  locale: LocaleCode,
  key: TranslationKey | string,
  ...args: unknown[]
): string {
  const resolve = (dict: Dictionary): unknown => {
    if (!KEY_RE.test(key)) return undefined;
    return key
      .split('.')
      .reduce<unknown>((node, part) => (node as Record<string, unknown>)?.[part], dict);
  };

  const value = resolve(dictionaries[locale]) ?? resolve(dictionaries.en);

  if (typeof value === 'function') {
    return (value as (...a: unknown[]) => string)(...args);
  }
  return typeof value === 'string' ? value : key;
}

/** Replaces `{name}` placeholders — used by the few strings with parameters. */
export function format(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}

/** Builds a translator bound to one locale. */
export function createTranslator(locale: LocaleCode) {
  return (key: TranslationKey | string, ...args: unknown[]) => translate(locale, key, ...args);
}